"""Landing page icons: the app's own CupertinoIcons, cut down to the few
the landing page uses, so the page and the app share one icon style.

    python tools/make_landing_icons.py

Writes landing/fonts/cupertino.woff (only the glyphs below) and
landing/icons.css (one `[data-i="name"]` rule per icon). In the HTML an
icon is `<span class="ms" data-i="cloud_fill" aria-hidden="true"></span>`;
names are the CupertinoIcons names you'd use in Dart. To add an icon, add
its name to ICONS and rerun. Edit this script, never the outputs.

Needs fontTools, the Flutter SDK on PATH (for the codepoints in
cupertino/icons.dart), and `flutter pub get` done once (for the font in
the pub cache). The font is MIT licensed (cupertino_icons package).
"""

import glob
import os
import re
import shutil
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_FONT = os.path.join(ROOT, 'landing', 'fonts', 'cupertino.woff')
OUT_CSS = os.path.join(ROOT, 'landing', 'icons.css')

ICONS = [
    # weather (same as weatherInfo() in lib/services/weather.dart)
    'sun_max_fill', 'moon_fill', 'cloud_fill', 'cloud_moon_fill', 'cloud_fog_fill',
    'cloud_drizzle_fill', 'drop_fill', 'snow', 'umbrella_fill', 'cloud_bolt_rain_fill',
    'drop', 'wind',
    # page
    'moon_stars_fill', 'xmark', 'info_circle_fill', 'arrow_right', 'arrow_down',
    'person_fill', 'eye_fill', 'camera_fill', 'location_solid', 'hand_thumbsup_fill',
    'trash', 'house_alt_fill', 'phone_fill', 'doc_on_doc', 'person_badge_plus_fill',
    'chevron_left_slash_chevron_right',
    # hotlines (same icons as kHotlines in lib/data/demo_data.dart)
    'exclamationmark_shield_fill', 'flame_fill', 'shield_fill', 'building_2_fill',
]


def codepoints():
    flutter = shutil.which('flutter')
    if not flutter:
        sys.exit('flutter is not on PATH')
    sdk = os.path.dirname(os.path.dirname(os.path.realpath(flutter)))
    src = open(os.path.join(sdk, 'packages', 'flutter', 'lib', 'src', 'cupertino', 'icons.dart'),
               encoding='utf-8').read()
    found = dict(re.findall(r'static const IconData (\w+) = IconData\(\s*(0x[0-9a-fA-F]+)', src))
    missing = [n for n in ICONS if n not in found]
    if missing:
        sys.exit('not in CupertinoIcons: ' + ', '.join(missing))
    return {n: int(found[n], 16) for n in ICONS}


def font_path():
    cache = os.environ.get('PUB_CACHE') or os.path.join(os.environ.get('LOCALAPPDATA', ''), 'Pub', 'Cache')
    hits = sorted(glob.glob(os.path.join(cache, 'hosted', 'pub.dev', 'cupertino_icons-*', 'assets', 'CupertinoIcons.ttf')))
    if not hits:
        sys.exit('CupertinoIcons.ttf not found: run `flutter pub get` first')
    return hits[-1]


def main():
    cps = codepoints()
    font = TTFont(font_path())
    sub = subset.Subsetter(subset.Options())
    sub.populate(unicodes=cps.values())
    sub.subset(font)
    font.flavor = 'woff'
    os.makedirs(os.path.dirname(OUT_FONT), exist_ok=True)
    font.save(OUT_FONT)

    rules = '\n'.join('[data-i="%s"]::before { content: "\\%x"; }' % (n, cp) for n, cp in cps.items())
    css = (
        '/* GENERATED by tools/make_landing_icons.py. Edit the script, not this file.\n'
        '   CupertinoIcons (MIT, the cupertino_icons package), the same set as the app. */\n\n'
        '@font-face {\n'
        '  font-family: "CupertinoIcons";\n'
        '  src: url("fonts/cupertino.woff") format("woff");\n'
        '  font-display: block;\n'
        '}\n\n' + rules + '\n'
    )
    with open(OUT_CSS, 'w', encoding='utf-8', newline='\n') as f:
        f.write(css)
    print('%d icons, %d bytes -> %s' % (len(cps), os.path.getsize(OUT_FONT), OUT_FONT))


if __name__ == '__main__':
    main()
